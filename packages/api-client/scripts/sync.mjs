// Copies the backend OpenAPI documents and regenerates typed paths.
//   yarn api:sync                       (backend repo next to this one: ../tutora)
//   BACKEND_OPENAPI_DIR=/path yarn api:sync
import { copyFileSync, existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const here = dirname(fileURLToPath(import.meta.url));
const pkg = resolve(here, '..');
const source = process.env.BACKEND_OPENAPI_DIR ?? resolve(pkg, '../../../tutora/docs/openapi');
const apps = ['student', 'tutor', 'admin', 'public'];

if (!existsSync(source)) {
  console.error(`Backend OpenAPI folder not found: ${source}\nRun "yarn openapi:export" in the backend, or set BACKEND_OPENAPI_DIR.`);
  process.exit(1);
}
mkdirSync(resolve(pkg, 'openapi'), { recursive: true });
mkdirSync(resolve(pkg, 'src/generated'), { recursive: true });
for (const app of apps) {
  const file = resolve(pkg, 'openapi', `${app}.json`);
  copyFileSync(resolve(source, `${app}.json`), file);
  const ast = await openapiTS(pathToFileURL(file));
  writeFileSync(
    resolve(pkg, 'src/generated', `${app}.ts`),
    `/* Generated by "yarn api:sync" from the backend OpenAPI document. Do not edit. */\n${astToString(ast)}`,
  );
  console.log(`generated src/generated/${app}.ts`);
}
